String chinesePath(String path) => path
    .split('/')
    .map(
      (part) => part.startsWith('node-')
          ? '模块${part.substring(5)}'
          : part.startsWith('part-')
          ? '子组件${part.substring(5)}'
          : chineseLabel(part),
    )
    .join(' / ');

